/*
 * Builds the route manifest: every route under `app/api/v1`, as it describes itself.
 *
 *   pnpm api:manifest           writes apps/web/src/server/manifest.ts
 *   pnpm api:manifest --check   changes nothing; exit 1 when the file is out of date
 *
 * Each route file is loaded and each handler it exports is asked what it is (`routeMetaOf`), so the
 * manifest says what the code does, not what a comment claims. A handler that was not made by one
 * of the route builders, or a route for members of a school that names no permission, stops the run.
 *
 * `pnpm api:verify-plan` compares the manifest with the plan, and
 * tests/api/security/routes.generated.test.ts calls every route in it.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';
import { routeMetaOf } from '@takhti/core';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const apiDir = resolve(here, '../app/api/v1');
const target = resolve(here, '../src/server/manifest.ts');
const checkOnly = process.argv.includes('--check');

const METHODS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'] as const;

function routeFiles(dir: string): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...routeFiles(path));
    else if (entry.name === 'route.ts') found.push(path);
  }
  return found;
}

interface Line {
  method: (typeof METHODS)[number];
  path: string;
  access: string;
  idempotent: boolean;
  rateLimit: 'standard' | 'none' | { max: number; windowSeconds: number; by: string };
}

const problems: string[] = [];
const lines: Line[] = [];

for (const file of routeFiles(apiDir)) {
  const path = `/${relative(apiDir, dirname(file)).split('\\').join('/')}`;
  const exported = (await import(pathToFileURL(file).href)) as Record<string, unknown>;
  let methods = 0;
  for (const method of METHODS) {
    const handler = exported[method];
    if (handler === undefined) continue;
    methods += 1;
    const meta = routeMetaOf(handler);
    if (!meta) {
      problems.push(
        `${method} ${path}: not made by a route builder (defineRoute and the others in @/server/route)`,
      );
      continue;
    }
    if (meta.access === undefined) {
      problems.push(
        `${method} ${path}: names no permission. Give defineRoute \`permission\`: a key, or 'signed-in'`,
      );
      continue;
    }
    lines.push({
      method,
      path,
      access: meta.access,
      idempotent: meta.idempotent,
      rateLimit: meta.rateLimit,
    });
  }
  if (methods === 0) problems.push(`${path}: the route file exports no handler`);
}

if (problems.length > 0) {
  console.error(problems.join('\n'));
  console.error(`\n${problems.length} problem(s). The manifest was not written.`);
  process.exit(1);
}

lines.sort(
  (a, b) =>
    a.path.localeCompare(b.path) || METHODS.indexOf(a.method) - METHODS.indexOf(b.method),
);

const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const entry = (line: Line): string => {
  const parts = [
    `method: ${quote(line.method)}`,
    `path: ${quote(line.path)}`,
    `access: ${quote(line.access)}`,
  ];
  if (line.idempotent) parts.push('idempotent: true');
  if (line.rateLimit === 'none') parts.push(`rateLimit: 'none'`);
  else if (line.rateLimit !== 'standard')
    parts.push(
      `rateLimit: { max: ${line.rateLimit.max}, windowSeconds: ${line.rateLimit.windowSeconds}, by: ${quote(line.rateLimit.by)} }`,
    );
  return `  { ${parts.join(', ')} },`;
};

const raw = `// Generated by \`pnpm api:manifest\` from the route files under app/api/v1. Do not edit.

/** One route of the API, as its handler describes itself. */
export interface ManifestRoute {
  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
  /** Under \`/api/v1\`, with parameters as the folders name them: \`/fee-vouchers/[id]/collect\`. */
  path: string;
  /** A permission key, or \`signed-in\`, \`public\`, \`platform\` or \`webhook\`. */
  access: string;
  /** The route requires an \`Idempotency-Key\` header. */
  idempotent?: true;
  /** The route's own limit, or \`none\`. Absent: the standard limit for its kind of route. */
  rateLimit?: 'none' | { max: number; windowSeconds: number; by: 'user' | 'ip' | 'org' };
}

export const routeManifest: readonly ManifestRoute[] = [
${lines.map(entry).join('\n')}
];
`;

const options = { ...(await prettier.resolveConfig(target)), filepath: target };
let content = raw;
// Prettier does not always settle in one pass on long lines.
for (let pass = 0; pass < 3; pass++) {
  const next = await prettier.format(content, options);
  if (next === content) break;
  content = next;
}

const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
const shown = relative(root, target).split('\\').join('/');
if (current === content) {
  console.log(`The route manifest is up to date: ${lines.length} route(s).`);
} else if (checkOnly) {
  console.error(`${shown} is out of date. Run \`pnpm api:manifest\`.`);
  process.exit(1);
} else {
  writeFileSync(target, content);
  console.log(`Wrote ${shown}: ${lines.length} route(s).`);
}
// Loading the routes loads the database client, which would keep the process alive.
process.exit(0);
