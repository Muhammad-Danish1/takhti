/*
 * Adds a wave's hand-written SQL to the migration drizzle-kit has just generated for it.
 *
 *   pnpm db:generate --name wave-3-academics
 *   pnpm db:custom-sql 3
 *
 * Drizzle cannot express exclusion constraints, views, triggers or partitions. Those statements are
 * kept in `packages/db/src/custom-sql/wave-N.sql` (written by `pnpm scaffold` from the hints) and
 * belong in the same migration as the tables they refer to. A conventions test checks that every
 * statement of every such file is present in a migration, so this step cannot be forgotten.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = resolve(here, '../../migrations');
const customDir = resolve(here, '../custom-sql');

const wave = Number(process.argv[2]);
if (!Number.isInteger(wave) || wave < 1) {
  console.error('Usage: pnpm db:custom-sql <wave number>');
  process.exit(1);
}

const source = join(customDir, `wave-${wave}.sql`);
if (!existsSync(source)) {
  console.log(`Wave ${wave} has no hand-written SQL; nothing to add.`);
  process.exit(0);
}

const folders = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const latest = folders.at(-1);
if (!latest || !latest.includes(`wave-${wave}-`)) {
  console.error(
    `The newest migration is "${latest ?? 'none'}", which is not Wave ${wave}'s. Generate the wave's migration first.`,
  );
  process.exit(1);
}

const target = join(migrationsDir, latest, 'migration.sql');
const marker = `-- Hand-written SQL for Wave ${wave} (packages/db/src/custom-sql/wave-${wave}.sql)`;
const current = readFileSync(target, 'utf8');
if (current.includes(marker)) {
  console.error(
    `"${latest}" already carries Wave ${wave}'s hand-written SQL. A migration is written once; add a new one for a change.`,
  );
  process.exit(1);
}

const statements = readFileSync(source, 'utf8')
  .split(/\r?\n/)
  .filter((line) => !line.startsWith('-- Generated by') && !line.startsWith('-- What Drizzle'))
  .join('\n')
  .trim();
writeFileSync(target, `${current.trimEnd()}\n\n${marker}\n\n${statements}\n`);
console.log(`Added Wave ${wave}'s hand-written SQL to ${latest}.`);
